/* The in-game guide, as a panel any page can mount: a list of topics on the left and the chosen topic on the right (paragraphs, steps, tips, warnings and tables).
   The text is guide-data.js, GENERATED by tools/build_guide.py from design/guide.json with every number read from the code, so it matches the rules. Used by
   guide.html (/ascend guide) and by the Guide tab of the AscensionDex (party.html). Needs ui.js and guide-data.js first. */
(function () {
  'use strict';
  var A = window.A;
  var STYLE = [
    '.gp { flex: 1; min-height: 0; display: flex; flex-direction: row !important; gap: 12px; }',
    '.gp .topics { width: 200px; flex: none; display: flex; flex-direction: column; gap: 4px; overflow-y: auto; }',
    '.gp .topics button { text-align: left; padding: 7px 10px; background: var(--row); border: 2px solid var(--line); box-shadow: none; }',
    '.gp .topics button.on { border-color: var(--acc); color: #fff; background: var(--panel); }',
    '.gp .content { flex: 1; min-width: 0; overflow-y: auto; padding: 4px 10px 12px 2px; display: flex; flex-direction: column; gap: 10px; }',
    '.gp h2 { margin: 0 0 2px; font-weight: 400; font-size: 16px; color: var(--acc); letter-spacing: .08em; text-transform: uppercase; text-shadow: var(--glow); }',
    '.gp .p { line-height: 1.5; }',
    '.gp ul, .gp ol { margin: 0; padding-left: 20px; display: flex; flex-direction: column; gap: 5px; line-height: 1.45; }',
    '.gp ol { list-style: none; padding-left: 0; counter-reset: step; }',
    '.gp ol li { counter-increment: step; display: grid; grid-template-columns: 28px 1fr; gap: 10px; align-items: start; }',
    '.gp ol li::before { content: counter(step); display: flex; align-items: center; justify-content: center; width: 24px; height: 24px; background: var(--crimson); color: #fff; border: 2px solid #eef2f7; }',
    '.gp .tip, .gp .warn { padding: 8px 10px; border-left: 4px solid var(--acc); background: var(--row); line-height: 1.45; }',
    '.gp .tip::before { content: "TIP  "; color: var(--acc); } .gp .warn { border-color: var(--warn); background: #2b1612; } .gp .warn::before { content: "NOTE  "; color: var(--warn); }',
    '.gp table { width: 100%; border-collapse: collapse; font-size: 11px; } .gp th { text-align: left; color: var(--muted); font-weight: 400; padding: 5px 8px; border-bottom: 2px solid var(--line); }',
    '.gp td { padding: 6px 8px; border-bottom: 1px solid var(--line); vertical-align: top; line-height: 1.4; } .gp td:first-child { color: var(--ink); white-space: nowrap; }',
    '.gp .nav { display: flex; justify-content: space-between; margin-top: 6px; }'
  ].join('\n');

  function el(tag, cls, text) { return A.el(tag, cls, text); }

  // The numbers a server owner can tune are {placeholders} in the text: the defaults ship in guide-data.js and the server sends its live values (and the live
  // completion-tier table), so a tuned server never shows a stale number.
  var facts = Object.assign({}, window.GUIDE && window.GUIDE.facts), liveTables = {};
  function fill(text) { return String(text).replace(/\{([a-zA-Z]+\.[a-zA-Z]+)\}/g, function (m, k) { return facts[k] !== undefined ? facts[k] : m; }); }

  function block(b) {
    if (b.type === 'p') return el('div', 'p', fill(b.text));
    if (b.type === 'tip' || b.type === 'warn') return el('div', b.type, fill(b.text));
    if (b.type === 'ul' || b.type === 'steps') {
      var list = el(b.type === 'ul' ? 'ul' : 'ol');
      b.items.forEach(function (i) { list.appendChild(el('li', '', fill(i))); });
      return list;
    }
    if (b.type === 'table') {
      var src = b.live && liveTables[b.live] ? liveTables[b.live] : b;
      var t = el('table'), head = el('tr');
      src.head.forEach(function (h) { head.appendChild(el('th', '', fill(h))); });
      t.appendChild(head);
      src.rows.forEach(function (row) { var r = el('tr'); row.forEach(function (c) { r.appendChild(el('td', '', fill(c))); }); t.appendChild(r); });
      return t;
    }
    return el('div');
  }

  /** Builds the panel in `root`. Returns {show(topicId)}; the first topic is open. */
  function mount(root) {
    if (!document.getElementById('gp-style')) { var st = document.createElement('style'); st.id = 'gp-style'; st.textContent = STYLE; document.head.appendChild(st); }
    root.className = (root.className ? root.className + ' ' : '') + 'gp';
    root.innerHTML = '';
    var data = window.GUIDE && window.GUIDE.topics ? window.GUIDE.topics : [];
    var list = el('div', 'topics'), content = el('div', 'content');
    root.appendChild(list); root.appendChild(content);
    var buttons = {}, current = -1;

    function show(id) {
      var index = 0;
      data.forEach(function (t, i) { if (t.id === id) index = i; });
      current = index;
      var topic = data[index];
      Object.keys(buttons).forEach(function (k) { buttons[k].className = k === topic.id ? 'on' : ''; });
      content.innerHTML = '';
      content.appendChild(el('h2', '', topic.title));
      topic.blocks.forEach(function (b) { content.appendChild(block(b)); });
      var nav = el('div', 'nav');
      var prev = el('button', '', index > 0 ? '< ' + data[index - 1].title : ''); prev.style.visibility = index > 0 ? 'visible' : 'hidden';
      prev.addEventListener('click', function () { show(data[current - 1].id); });
      var next = el('button', '', index < data.length - 1 ? data[index + 1].title + ' >' : ''); next.style.visibility = index < data.length - 1 ? 'visible' : 'hidden';
      next.addEventListener('click', function () { show(data[current + 1].id); });
      nav.appendChild(prev); nav.appendChild(next); content.appendChild(nav);
      content.scrollTop = 0;
    }

    if (!data.length) { content.appendChild(el('div', 'p', 'The guide is not available.')); return { show: function () {} }; }
    data.forEach(function (t) {
      var b = el('button', '', t.title);
      b.addEventListener('click', function () { show(t.id); });
      buttons[t.id] = b; list.appendChild(b);
    });
    show(data[0].id);
    // the live numbers: asked for once, and redrawn when they arrive
    A.on('guideFacts', function (m) {
      if (m && m.facts) Object.keys(m.facts).forEach(function (k) { facts[k] = m.facts[k]; });
      if (m && m.tables) liveTables = m.tables;
      if (current >= 0) show(data[current].id);
    });
    if (A.g) A.send('ascension_guide_facts');
    return { show: show };
  }

  A.guide = { mount: mount };
})();
